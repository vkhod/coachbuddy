// The service worker (Phase 4 step 2), hand-written on purpose (decided
// 2026-11-24): no dependency to keep in step with Next and Turbopack.
//
// /sw.js (src/app/sw.js/route.ts) serves this script with three values filled
// in: the version (build id plus branding version), the static files of this
// build, and the pages to keep from the start. A new build or a changed
// branding gives a new script, the browser installs it as a waiting worker,
// and the page offers "New version available" (ServiceWorker.tsx). The worker
// never takes over by itself while a page is open.
//
// What it caches, all same-origin GET requests:
//   - /_next/static/* (JS, CSS, fonts): precached at install, then cache first.
//     The file names carry a content hash, so a cached copy is never stale.
//   - /brand/* and the manifest: served from the cache, refreshed in the
//     background.
//   - Pages (navigations): network first. A good answer is kept under its
//     path; offline, or after NAV_TIMEOUT_MS without an answer, the kept copy
//     is used. With no kept copy, a short offline page links to History.
//   - "cache-page" messages from the app keep a page it will need offline
//     (step 3 sends one for each plan it saves).
// It never touches the gateway (another origin until Phase 6, then /api/),
// RSC requests, or the share pages. Offline, an RSC request fails, Next falls
// back to a full page load, and the page comes from the kept copy.
//
// The worker never stores or builds plan content: plans for offline reading
// are saved by the app itself, from what the gateway returned (step 3).

export interface WorkerConfig {
  version: string;
  assets: string[];
  pages: string[];
  paper: string;
  ink: string;
}

export const NAV_TIMEOUT_MS = 4000;

export function workerScript(cfg: WorkerConfig): string {
  return `// Coach Buddy service worker. Generated by /sw.js; see src/lib/sw-script.ts.
"use strict";
const VERSION = ${JSON.stringify(cfg.version)};
const ASSETS = ${JSON.stringify(cfg.assets)};
const PAGES = ${JSON.stringify(cfg.pages)};
const NAV_TIMEOUT_MS = ${NAV_TIMEOUT_MS};
const STATIC = "cb-static-" + VERSION;
const PAGE_CACHE = "cb-pages";
const BRAND = "cb-brand-" + VERSION;
const OFFLINE_HTML = ${JSON.stringify(offlinePage(cfg))};

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const s = await caches.open(STATIC);
      await s.addAll(ASSETS);
      const p = await caches.open(PAGE_CACHE);
      // Every kept page is fetched again with this build: an old copy points at
      // the old build's JS files, which activate deletes. One that fails to
      // fetch stays as it was.
      const kept = (await p.keys()).map((r) => new URL(r.url).pathname);
      const paths = [...new Set([...PAGES, ...kept])];
      await Promise.all(
        paths.map(async (path) => {
          try {
            const res = await fetch(path, { cache: "no-store", credentials: "same-origin" });
            if (res.ok) await p.put(path, res);
          } catch (e) {}
        }),
      );
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keep = new Set([STATIC, PAGE_CACHE, BRAND]);
      for (const key of await caches.keys()) {
        if (key.startsWith("cb-") && !keep.has(key)) await caches.delete(key);
      }
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("message", (event) => {
  const msg = event.data || {};
  if (msg.type === "skip-waiting") self.skipWaiting();
  if (msg.type === "cache-page" && typeof msg.path === "string" && keepPage(msg.path)) {
    event.waitUntil(
      fetch(msg.path, { cache: "no-store", credentials: "same-origin" })
        .then((res) => (res.ok ? caches.open(PAGE_CACHE).then((c) => c.put(msg.path, res)) : undefined))
        .catch(() => undefined),
    );
  }
  if (msg.type === "drop-pages") {
    // Sign out: plan pages go; the shared pages (Capture, History, login) stay.
    event.waitUntil(
      caches.open(PAGE_CACHE).then(async (c) => {
        for (const req of await c.keys()) {
          if (!PAGES.includes(new URL(req.url).pathname)) await c.delete(req);
        }
      }),
    );
  }
});

/** Pages worth keeping for offline use. Not the share pages, versions or settings. */
function keepPage(path) {
  return PAGES.includes(path) || /^\\/plans\\/[^/]+$/.test(path);
}

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith("/api/") || url.pathname === "/sw.js") return;
  if (req.headers.get("RSC") || url.searchParams.has("_rsc")) return;

  if (url.pathname.startsWith("/_next/static/")) {
    event.respondWith(cacheFirst(req));
  } else if (url.pathname.startsWith("/brand/") || url.pathname === "/manifest.webmanifest") {
    event.respondWith(staleWhileRevalidate(req, event));
  } else if (req.mode === "navigate") {
    event.respondWith(page(req, url.pathname, event));
  }
});

async function cacheFirst(req) {
  const hit = await caches.match(req);
  if (hit) return hit;
  const res = await fetch(req);
  if (res.ok) (await caches.open(STATIC)).put(req, res.clone());
  return res;
}

async function staleWhileRevalidate(req, event) {
  const cache = await caches.open(BRAND);
  const hit = await cache.match(req);
  const fresh = fetch(req)
    .then((res) => {
      if (res.ok) return cache.put(req, res.clone()).then(() => res);
      return res;
    })
    .catch(() => undefined);
  if (hit) {
    event.waitUntil(fresh);
    return hit;
  }
  return (await fresh) || Response.error();
}

async function page(req, path, event) {
  const cache = await caches.open(PAGE_CACHE);
  const network = fetch(req).then((res) => {
    if (res.ok && keepPage(path)) event.waitUntil(cache.put(path, res.clone()));
    return res;
  });
  const kept = await cache.match(path);
  if (!kept) {
    try {
      return await network;
    } catch (e) {
      return new Response(OFFLINE_HTML, { status: 503, headers: { "Content-Type": "text/html; charset=utf-8" } });
    }
  }
  // A slow network (a box with one bar of signal) falls back to the kept copy.
  const timeout = new Promise((resolve) => setTimeout(() => resolve(null), NAV_TIMEOUT_MS));
  try {
    const res = await Promise.race([network, timeout]);
    if (res) return res;
  } catch (e) {}
  network.catch(() => undefined);
  return kept;
}
`;
}

function offlinePage({ paper, ink }: WorkerConfig): string {
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Offline</title>
<style>body{margin:0;padding:2rem 1rem;font:1rem/1.5 system-ui,sans-serif;background:${paper};color:${ink}}a{color:${ink};display:inline-block;min-height:44px;line-height:44px}</style></head>
<body><h1 style="font-size:1.25rem">You are offline</h1><p>This page was not saved on the phone. Plans you opened before are in History.</p><p><a href="/history">Open History</a></p></body></html>`;
}
